-- =========================================================================
-- AGENT : SELECT sur toutes les tables/vues des 9 schemas, rien d'autre
-- =========================================================================
BEGIN
  FOR r IN (
    SELECT owner, table_name obj FROM all_tables
    WHERE owner IN ('SDASTG','SDATRG','SDAINT','SDESTG','SDETRG','SDEINT','DMDSTG','DMDTRG','DMDINT')
    UNION ALL
    SELECT owner, view_name FROM all_views
    WHERE owner IN ('SDASTG','SDATRG','SDAINT','SDESTG','SDETRG','SDEINT','DMDSTG','DMDTRG','DMDINT')
  ) LOOP
    EXECUTE IMMEDIATE 'GRANT SELECT ON '||r.owner||'.'||r.obj||' TO AGENT';
  END LOOP;
END;
