-- Operation volumineuse (simule les gros traitements DMD a base de CTE imbriquees)
INSERT INTO DMDTRG.M_OPERATION VALUES ('BANK','DMD_LOAD','W_CLIENT_360',4,4,'DMDTRG.W_CLIENT_360', q'[
WITH
base_tiers AS (
  SELECT ID_TIERS, NOM, PRENOM, SEGMENT, PAYS, DATE_CREATION
  FROM DMDTRG.D_TIERS
),
base_ops AS (
  SELECT ID_TIERS, ID_COMPTE, DATE_OPERATION, MONTANT, DEVISE, TYPE_OPERATION
  FROM DMDTRG.F_OPERATION
  WHERE DATE_OPERATION <= TO_DATE('#PNDATE#','YYYYMMDD')
),
ops_valorisees AS (
  SELECT
    ID_TIERS,
    MONTANT,
    DATE_OPERATION,
    TYPE_OPERATION,
    CASE
      WHEN TYPE_OPERATION = 'VIREMENT'    THEN MONTANT
      WHEN TYPE_OPERATION = 'PAIEMENT_CB' THEN MONTANT
      WHEN TYPE_OPERATION = 'PRELEVEMENT' THEN -ABS(MONTANT)
      WHEN TYPE_OPERATION = 'RETRAIT'     THEN -ABS(MONTANT)
      ELSE MONTANT
    END AS MONTANT_SIGNE
  FROM base_ops
),
agg_tiers AS (
  SELECT
    ID_TIERS,
    COUNT(*)                         AS NB_OPERATIONS,
    SUM(MONTANT_SIGNE)               AS MONTANT_TOTAL,
    ROUND(AVG(MONTANT_SIGNE), 2)     AS MONTANT_MOYEN,
    MAX(DATE_OPERATION)              AS DATE_DERNIERE_OPERATION
  FROM ops_valorisees
  GROUP BY ID_TIERS
),
canal_tiers AS (
  SELECT
    ID_TIERS,
    TYPE_OPERATION AS CANAL_PREFERE,
    ROW_NUMBER() OVER (
      PARTITION BY ID_TIERS
      ORDER BY COUNT(*) DESC, TYPE_OPERATION
    ) AS RANG_CANAL
  FROM ops_valorisees
  GROUP BY ID_TIERS, TYPE_OPERATION
),
canal_retenu AS (
  SELECT ID_TIERS, CANAL_PREFERE
  FROM canal_tiers
  WHERE RANG_CANAL = 1
),
scoring AS (
  SELECT
    A.ID_TIERS,
    A.NB_OPERATIONS,
    A.MONTANT_TOTAL,
    A.MONTANT_MOYEN,
    A.DATE_DERNIERE_OPERATION,
    CASE
      WHEN A.MONTANT_TOTAL < 0 AND A.NB_OPERATIONS > 5 THEN 'HAUT'
      WHEN A.MONTANT_TOTAL < 0                          THEN 'MOYEN'
      WHEN A.NB_OPERATIONS = 0                           THEN 'INCONNU'
      ELSE 'BAS'
    END AS SCORE_RISQUE,
    CASE
      WHEN A.DATE_DERNIERE_OPERATION >= TO_DATE('#PNDATE#','YYYYMMDD') - 7 THEN 'ACTIF'
      WHEN A.DATE_DERNIERE_OPERATION >= TO_DATE('#PNDATE#','YYYYMMDD') - 30 THEN 'DORMANT'
      ELSE 'INACTIF'
    END AS STATUT
  FROM agg_tiers A
)
SELECT
  T.ID_TIERS,
  T.NOM,
  T.PRENOM,
  T.SEGMENT,
  T.PAYS,
  NVL(S.NB_OPERATIONS, 0)            AS NB_OPERATIONS,
  NVL(S.MONTANT_TOTAL, 0)            AS MONTANT_TOTAL,
  NVL(S.MONTANT_MOYEN, 0)            AS MONTANT_MOYEN,
  S.DATE_DERNIERE_OPERATION,
  T.DATE_CREATION,
  NVL(S.STATUT, 'INACTIF')           AS STATUT,
  C.CANAL_PREFERE,
  NVL(S.SCORE_RISQUE, 'INCONNU')     AS SCORE_RISQUE
FROM base_tiers T
LEFT JOIN scoring S ON S.ID_TIERS = T.ID_TIERS
LEFT JOIN canal_retenu C ON C.ID_TIERS = T.ID_TIERS
]');

