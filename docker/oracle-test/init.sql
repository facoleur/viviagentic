CREATE VIEW SDAINT.V_TIERS AS SELECT * FROM SDATRG.TIERS;
CREATE VIEW SDAINT.V_MOUVEMENT AS SELECT * FROM SDATRG.MOUVEMENT;
-- Colonnes de la prod (voir framework.COLUMNS) : target_table est sans schema.
CREATE VIEW SDAINT.V_M_OPERATION AS SELECT CHAINE CHAIN_NAME, FLUX FLOW_NAME, ORDRE OPERATION_NR,
  SQL_TEXT OPERATION, 'Alimente ' || TABLE_CIBLE OPERATION_DESCRIPTION,
  SUBSTR(TABLE_CIBLE, 1, INSTR(TABLE_CIBLE, '.') - 1) TARGET_SCHEMA,
  SUBSTR(TABLE_CIBLE, INSTR(TABLE_CIBLE, '.') + 1) TARGET_TABLE,
  DATE '9999-12-31' VALIDITY_END_DATE, CAST(NULL AS VARCHAR2(30)) INSTRUCTION
  FROM SDATRG.M_OPERATION;
-- Colonnes de la prod : zone de la source, source et cible sans schema ni prefixe V_.
CREATE VIEW DMDINT.V_M_TRAC_DATA AS SELECT t.*, CHAINE CHAIN_NAME,
  SUBSTR(TABLE_SOURCE, 1, 3) SOURCE_APPLICATION_CODE, 'flow' TARGET_TYPE,
  REGEXP_REPLACE(SUBSTR(TABLE_SOURCE, INSTR(TABLE_SOURCE, '.') + 1), '^V_') SOURCE_NAME,
  SUBSTR(TABLE_CIBLE, INSTR(TABLE_CIBLE, '.') + 1) TARGET_NAME,
  DATE '9999-12-31' VALIDITY_END_DATE
  FROM DMDTRG.TRAC_DATA t;
CREATE VIEW DMDINT.V_M_LOG AS SELECT * FROM DMDTRG.OPERATION_LOG_HEADER;
CREATE VIEW DMDINT.V_M_FLOWDATA AS SELECT CHAINE CHAIN_NAME, FLUX FLOW_NAME,
  MIN(ORDRE) SEQ_NR, 'DAILY' LOAD_FREQUENCY, 'Y' ACTIVE_FLAG, DATE '9999-12-31' VALIDITY_END_DATE
  FROM DMDTRG.M_OPERATION GROUP BY CHAINE, FLUX;

-- =========================================================================
-- AGENT : SELECT sur toutes les tables/vues des 9 schemas, rien d'autre
-- =========================================================================
BEGIN
  FOR r IN (
    SELECT owner, table_name obj FROM all_tables
    WHERE owner IN ('SDASTG','SDATRG','SDAINT','SDESTG','SDETRG','SDEINT','DMDSTG','DMDTRG','DMDINT')
    UNION ALL
    SELECT owner, view_name FROM all_views
    WHERE owner IN ('SDASTG','SDATRG','SDAINT','SDESTG','SDETRG','SDEINT','DMDSTG','DMDTRG','DMDINT')
  ) LOOP
    EXECUTE IMMEDIATE 'GRANT SELECT ON '||r.owner||'.'||r.obj||' TO AGENT';
  END LOOP;
END;
